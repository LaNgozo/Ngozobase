    private void btnUploadAssignmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUploadAssignmentActionPerformed
     // Opens the Upload Assignment Dialog (Modal)
  //  UploadAssignmentDialog dialog = new UploadAssignmentDialog(this, true);
  //  dialog.setVisible(true);   // TODO add your handling code here:
    
    	// --- 1. UPLOAD ASSIGNMENT BUTTON ---
	// Opens a file picker so teachers can upload class documents or homework files
	btnUploadAssignment.addActionListener(e -> {
	    JFileChooser fileChooser = new JFileChooser();
	    fileChooser.setDialogTitle("Select Assignment File to Upload");
	    	    int userSelection = fileChooser.showOpenDialog(TeacherHomeFrame.this);
	    if (userSelection == JFileChooser.APPROVE_OPTION) {
	        String fileName = fileChooser.getSelectedFile().getName();
	        JOptionPane.showMessageDialog(
	            TeacherHomeFrame.this,
	            "Successfully uploaded: " + fileName + "\nAssigned to active class.",
	            "Upload Complete",
	            JOptionPane.INFORMATION_MESSAGE
	        );
	    }
	});

    }//GEN-LAST:event_btnUploadAssignmentActionPerformed

