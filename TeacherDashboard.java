    private void btnAddCommentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddCommentActionPerformed
        // TODO add your handling code here:
        	// --- 4. ADD COMMENT BUTTON ---
	// Prompts the teacher to enter a quick academic progress note for a student
	btnAddComment.addActionListener(e -> {
	    String studentName = JOptionPane.showInputDialog(
	        TeacherHomeFrame.this,
	        "Enter Student Name or ID:",
	        "Add Academic Comment",
	        JOptionPane.QUESTION_MESSAGE
	    );
	
	    if (studentName != null && !studentName.trim().isEmpty()) {
	        String comment = JOptionPane.showInputDialog(
	            TeacherHomeFrame.this,
	            "Enter academic remark for " + studentName + ":",
	            "Teacher Feedback",
	            JOptionPane.PLAIN_MESSAGE
	        );
	
	        if (comment != null && !comment.trim().isEmpty()) {
	            JOptionPane.showMessageDialog(
	                TeacherHomeFrame.this,
	                "Comment saved to " + studentName + "'s profile!",
	                "Success",
	                JOptionPane.INFORMATION_MESSAGE
	            );
	        }
	    }
	});

    }//GEN-LAST:event_btnAddCommentActionPerformed

